const TABLE = new Uint32Array(256);
for (let i = 0; i < 128; i++) {
  TABLE[i] = i;
}
for (let i = 128; i < 256; i++) {
  TABLE[i] = 0xfffd;
}
for (const sourceMap of [PSEUDO_GRAPHICS, KOI8R_RUSSIAN_UPPER, KOI8R_RUSSIAN_LOWER]) {
  for (const key in sourceMap) {
    const k = Number(key);
    if (k >= 0 && k < 256) {
      TABLE[k] = sourceMap[k];
    }
  }
}

export function decodeBytes(bytes) {
  if (bytes === null || bytes === undefined) {
    throw new TypeError('Input must be a Uint8Array or array-like of bytes');
  }
  const length = bytes.length >>> 0;
  let out = '';
  for (let i = 0; i < length; i++) {
    const cp = TABLE[bytes[i] & 0xff];
    out += String.fromCodePoint(cp);
  }
  return out;
}

export function decodeString(input) {
  if (typeof input !== 'string') {
    throw new TypeError('Input must be a string with each character in the 0-255 range');
  }
  const length = input.length >>> 0;
  let out = '';
  for (let i = 0; i < length; i++) {
    const b = input.charCodeAt(i);
    const cp = TABLE[b & 0xff];
    out += String.fromCodePoint(cp);
  }
  return out;
}

export function validate(bytes) {
  if (bytes === null || bytes === undefined) {
    throw new TypeError('Input must be a Uint8Array or array-like of bytes');
  }
  const length = bytes.length >>> 0;
  const invalid = [];
  for (let i = 0; i < length; i++) {
    const b = bytes[i] & 0xff;
    if (TABLE[b] === 0xfffd) {
      invalid.push(i);
    }
  }
  return { valid: invalid.length === 0, invalidBytes: invalid };
}
